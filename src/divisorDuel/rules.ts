export type ComboTier = (typeof RULES.comboTiers)[number]

/** หาชั้นโบนัสคอมโบจากจำนวน Critical Hit ติดต่อกัน */
export function getComboTier(streak: number): ComboTier | null {
  return RULES.comboTiers.find((tier) => streak >= tier.streak) ?? null
}

export function getComboBonusPercent(streak: number): number {
  return getComboTier(streak)?.bonusPercent ?? 0
}
