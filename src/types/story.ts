/** ช่วงเวลาที่ตอนนี้ถูกเล่า */
export type StoryMoment = 'before' | 'after'

export interface StoryBeat {
  id: string
  /** ด่านที่ทำให้ตอนนี้ถูกเล่า */
  stageId: string
  /** เล่าก่อนเข้าด่าน หรือหลังผ่านด่าน */
  moment: StoryMoment
  /** ผู้พูด ถ้าไม่ระบุคือเสียงบรรยาย */
  npcId?: string
  title: string
  /** ข้อความหลายย่อหน้า แสดงทีละย่อหน้าให้เด็กอ่านทัน */
  lines: string[]
  /** ธงที่ได้เมื่ออ่านจบ */
  grantsFlag?: string
}

/** บทพูดของ NPC ที่เปลี่ยนไปตามธงที่เด็กมี */
export interface NpcLine {
  npcId: string
  /**
   * ต้องมีธงเหล่านี้ครบจึงจะพูดประโยคนี้
   * ถ้าไม่ระบุคือพูดได้ตลอด ใช้เป็นประโยคเริ่มต้น
   */
  requiresFlags?: string[]
  /** ถ้ามีธงเหล่านี้อยู่ จะไม่พูดประโยคนี้ ใช้กันประโยคเก่าค้าง */
  hiddenByFlags?: string[]
  text: string
}

/** หนึ่งบทของการผจญภัย ใช้จัดกลุ่มตอนให้อ่านย้อนหลังได้ */
export interface StoryChapter {
  id: string
  worldId: string
  title: string
  summary: string
  beatIds: string[]
}
