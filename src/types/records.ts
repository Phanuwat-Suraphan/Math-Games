/**
 * สมุดสถิติของโหมดที่จบในรอบเดียว
 *
 * ทำไมต้องมีที่เก็บแยก
 *
 * ด่านเนื้อเรื่องทิ้งร่องรอยไว้ในตัวผู้เล่นอยู่แล้ว ผ่านด่านไหนบ้าง ได้กี่ดาว
 * เปิดหน้าความสำเร็จเมื่อไรก็ย้อนดูได้ตลอด
 *
 * แต่สนามรบ ศึกผ่าสมการ และหอคอย ไม่ทิ้งอะไรไว้เลย
 * จบรอบแล้วทุกอย่างหายไปพร้อมกับหน้าจอสรุป เหลือแค่เหรียญที่ได้
 * เด็กที่รอดในสนามรบได้เจ็ดนาที หรือชนะศึกผ่าสมการสิบครั้ง
 * จึงไม่มีอะไรยืนยันว่าเคยทำได้ นอกจากความทรงจำของตัวเอง
 *
 * ไฟล์นี้คือที่เก็บร่องรอยเหล่านั้น เพื่อให้ความสำเร็จอ้างอิงได้
 * และเพื่อให้สิ่งที่เด็กทำได้ในโหมดเหล่านี้ไม่หายไปเฉย ๆ
 *
 * หลักที่ยึด: เก็บเฉพาะตัวเลขสรุป ไม่เก็บประวัติรายรอบ
 * เพราะข้อมูลทั้งหมดอยู่ใน localStorage ซึ่งมีเพดานความจุ
 * และประวัติรายรอบจะโตขึ้นเรื่อย ๆ ไม่มีวันหยุด
 */

export interface PlayerRecords {
  /** เล่นสนามรบไปกี่รอบ นับทุกรอบที่จบ ไม่ว่าจะตายหรือกดจบเอง */
  survivorRuns: number
  /** เวลารอดที่ดีที่สุด หน่วยวินาที */
  survivorBestSeconds: number
  /** จำนวนมอนสเตอร์ที่ล้มได้ รวมทุกรอบ */
  survivorKills: number
  /** จำนวนบอสที่ล้มได้ รวมทุกรอบ */
  survivorBossKills: number
  /**
   * รหัสอาวุธที่เคยปลุกร่างสมบูรณ์ได้อย่างน้อยหนึ่งครั้ง
   *
   * เก็บเป็นรายการรหัส ไม่ใช่จำนวนครั้ง เพราะสิ่งที่อยากให้เด็กไล่เก็บ
   * คือการได้ครบทุกแบบ ไม่ใช่การทำแบบเดิมซ้ำ ๆ ให้ครบจำนวน
   */
  survivorEvolutions: string[]
  /** ใช้สกิลวิเศษไปทั้งหมดกี่ครั้ง */
  survivorUltimates: number

  /** เล่นศึกผ่าสมการไปกี่ตา */
  duelPlays: number
  /** ชนะศึกผ่าสมการไปกี่ครั้ง */
  duelWins: number

  /** ชั้นหอคอยที่สูงที่สุดที่เคยผ่านได้ */
  towerBestFloor: number

  /** เล่นผจญภัยเมืองแห่งเวลาจบไปกี่เกม */
  timePlays: number
  /** เกมที่มีคนในวงเข้าปราสาทเวลาได้ */
  timeCastles: number
  /**
   * ตอบการ์ดเวลาถูกรวมกี่ข้อ
   *
   * นับของทุกคนในวง เพราะเกมนี้เล่นหลายคนบนเครื่องเดียว
   * และเครื่องนั้นมีบัญชีผู้เล่นบัญชีเดียว
   */
  timeCorrect: number

  /** เล่น ZOMBIE RESCUE จบไปกี่เกม */
  zombiePlays: number
  /** เกมที่ทีมสร้าง Z-CURE สำเร็จ */
  zombieCures: number
  /**
   * ตอบโจทย์การคูณถูกรวมกี่ข้อ ทั้งเกมกระดานและโหมดฝึกสูตรคูณ
   * นับของทุกคนในวง ด้วยเหตุผลเดียวกับ timeCorrect
   */
  zombieCorrect: number
  /**
   * สติกเกอร์ในสมุดวัคซีนที่ได้แล้ว (0–50)
   * ตัวสมุดเก็บแยกคีย์ใน localStorage ค่านี้เป็นสำเนาจำนวนไว้ให้ถ้วยรางวัลกับหอเกียรติยศอ่าน
   * สติกเกอร์ไม่มีวันหาย ค่านี้จึงเก็บเฉพาะค่าที่มากที่สุด
   */
  zombieStickers: number
}
