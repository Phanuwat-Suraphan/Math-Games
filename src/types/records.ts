export interface PlayerRecords {
  /** เล่นสนามรบไปกี่รอบ นับทุกรอบที่จบ ไม่ว่าจะตายหรือกดจบเอง */
  survivorRuns: number
  /** เวลารอดที่ดีที่สุด หน่วยวินาที */
  survivorBestSeconds: number
  /** จำนวนมอนสเตอร์ที่ล้มได้ รวมทุกรอบ */
  survivorKills: number
  /** จำนวนบอสที่ล้มได้ รวมทุกรอบ */
  survivorBossKills: number
  /**
   * รหัสอาวุธที่เคยปลุกร่างสมบูรณ์ได้อย่างน้อยหนึ่งครั้ง
   *
   * เก็บเป็นรายการรหัส ไม่ใช่จำนวนครั้ง เพราะสิ่งที่อยากให้เด็กไล่เก็บ
   * คือการได้ครบทุกแบบ ไม่ใช่การทำแบบเดิมซ้ำ ๆ ให้ครบจำนวน
   */
  survivorEvolutions: string[]
  /** ใช้สกิลวิเศษไปทั้งหมดกี่ครั้ง */
  survivorUltimates: number

  /** เล่นศึกผ่าสมการไปกี่ตา */
  duelPlays: number
  /** ชนะศึกผ่าสมการไปกี่ครั้ง */
  duelWins: number

  /** ชั้นหอคอยที่สูงที่สุดที่เคยผ่านได้ */
  towerBestFloor: number
}
