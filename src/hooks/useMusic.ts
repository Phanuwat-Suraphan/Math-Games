/**
 * ให้หน้าจอบอกว่าตัวเองควรมีเพลงอะไร
 *
 * ทำไมเป็นฮุกที่ผูกกับหน้าจอ ไม่ใช่ตัวจัดการกลางที่ดูเส้นทาง URL
 *
 * เพลงในเกมนี้ไม่ได้เปลี่ยนตามหน้าอย่างเดียว แต่เปลี่ยนตามสิ่งที่เกิดขึ้นในหน้าด้วย
 * สนามรบเปลี่ยนเป็นเพลงบอสตอนบอสโผล่ แล้วเปลี่ยนกลับตอนบอสตาย
 * ตัวจัดการกลางที่ดูแค่ URL จะไม่มีทางรู้เรื่องพวกนี้เลย
 * และการให้มันรู้ก็แปลว่าต้องยกสถานะของแต่ละโหมดขึ้นไปไว้ข้างบน
 * ซึ่งแพงกว่าปัญหาที่แก้มาก
 *
 * ส่งค่า null เข้ามาได้ แปลว่าหน้านี้ไม่อยากได้เพลง
 */

import { useEffect } from 'react'
import { playMusic, stopMusic } from '../services/musicService'
import type { TrackId } from '../audio/theme'

export function useMusic(track: TrackId | null): void {
  useEffect(() => {
    if (!track) {
      stopMusic()
      return
    }
    playMusic(track)
  }, [track])

  /*
   * หยุดเพลงตอนออกจากหน้า แยกเป็น effect ของตัวเองที่ไม่มี dependency
   *
   * ถ้ารวมไว้กับข้างบน การเปลี่ยนเพลงภายในหน้าเดียวกัน (เช่นบอสโผล่)
   * จะกลายเป็นหยุดแล้วเริ่มใหม่ทุกครั้ง ซึ่งได้ยินเป็นเสียงสะดุด
   * ส่วน playMusic เองรู้อยู่แล้วว่าต้องข้ามเพลงเดิมให้เนียน
   */
  useEffect(() => stopMusic, [])
}
