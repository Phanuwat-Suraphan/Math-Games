export type SlotState = 'good' | 'try'

/**
 * ความคืบหน้าภารกิจหลังตอบหนึ่งครั้ง
 * ข้อหลักเสร็จเมื่อ ตอบถูก (ช่องได้ของประจำภารกิจ) หรือ ผิดครบ 2 ครั้ง (ช่อง 💪 ไม่เป็นไร ลองใหม่ได้)
 * ข้อฝึกซ้ำที่เพิ่มต่อท้ายไม่นับเป็นช่องใหม่
 */
export function advanceMission(slots: readonly SlotState[], correct: boolean, attempt: number, retry: boolean): SlotState[] {
  if (retry) return slots.slice()
  if (correct) return [...slots, 'good']
  if (attempt >= 2) return [...slots, 'try']
  return slots.slice()
}
