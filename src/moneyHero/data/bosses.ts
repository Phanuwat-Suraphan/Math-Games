export function bossOf(level: number): Boss {
  return BOSSES[level] ?? BOSSES[0]
}

/** จำนวนข้อที่ต้องตอบถูก (ภายใน 2 ครั้ง) เพื่อชนะ = พลังชีวิตของบอส */
export function bossHp(questions: number, pass: number): number {
  return Math.max(1, Math.ceil(questions * pass))
}
