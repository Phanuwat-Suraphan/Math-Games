export function getStagesByWorld(worldId: string): Stage[] {
  return STAGES.filter((stage) => stage.worldId === worldId).sort(
    (a, b) => a.order - b.order,
  )
}

export function getStage(stageId: string): Stage | undefined {
  return STAGES.find((stage) => stage.id === stageId)
}

/** ด่านถัดไปในโลกเดียวกัน คืน undefined เมื่อเป็นด่านสุดท้าย */
export function getNextStage(stage: Stage): Stage | undefined {
  return getStagesByWorld(stage.worldId).find(
    (candidate) => candidate.order === stage.order + 1,
  )
}

/** จำนวนดาวสูงสุดที่เก็บได้ในโลกหนึ่ง */
export function getMaxStarsForWorld(worldId: string): number {
  return getStagesByWorld(worldId).length * 3
}
