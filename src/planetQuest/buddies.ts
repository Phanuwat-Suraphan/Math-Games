export function buddyFor(id: PlanetId): Buddy {
  const found = BUDDIES.find((buddy) => buddy.id === id)
  if (!found) throw new Error(`ไม่มีเพื่อนดาวของ ${id}`)
  return found
}

/** เลือกประโยคแบบวนไปเรื่อย ๆ ดาวจะไม่พูดประโยคเดิมติดกันสองครั้ง */
export function lineFor(lines: readonly string[], count: number): string {
  if (lines.length === 0) return ''
  return lines[((count % lines.length) + lines.length) % lines.length]
}

/** ตอบถูกติดกันตั้งแต่สามครั้ง ดาวพูดเรื่องคอมโบแทนประโยคเชียร์ปกติ */
export const COMBO_FROM = 3

export function comboLine(streak: number): string {
  if (streak >= 6) return `คอมโบ ${streak}! ร้อนแรงกว่าดวงอาทิตย์อีก ☀️🔥`
  if (streak >= 4) return `คอมโบ ${streak}! หยุดไม่อยู่แล้ว 🚀`
  return `คอมโบ ${streak}! ไฟลุกแล้ว 🔥`
}

/** ก่อนตอบข้อแรก ดาวเจ้าบ้านส่งเสียงเชียร์รอไว้ */
export function readyLine(buddy: Buddy): string {
  return `สู้ ๆ นะ! ${buddy.nickname}เชียร์อยู่ตรงนี้ 📣`
}

/** ดาวที่ยังไม่มีใครไปเยี่ยมหลับอยู่ */
export function sleepyLine(buddy: Buddy): string {
  return `zZ… ${buddy.nickname}ยังหลับอยู่ บินมาปลุกหน่อยนะ`
}

/** ประโยคแรกตอนเพิ่งถูกปลุกเป็นครั้งแรก */
export function wakeLine(buddy: Buddy): string {
  return `ฮ้าว~ ใครมาปลุก${buddy.nickname}น่ะ… ว้าว มีเพื่อนมาเที่ยว ดีใจจัง!`
}

/** ลาตอนเล่นจบ ยิ่งได้ดาวมากยิ่งดีใจ แต่ดาวเดียวก็ยังขอบคุณ */
export function goodbyeLine(buddy: Buddy, stars: Stars): string {
  if (stars === 3) return `สามดาวเลย! ${buddy.nickname}ปลื้มสุด ๆ 💖`
  if (stars === 2) return `เก่งมาก! แวะมาเล่นกับ${buddy.nickname}อีกนะ`
  return `ขอบคุณที่มาเยี่ยม${buddy.nickname}นะ ครั้งหน้าลุยใหม่ได้เสมอ!`
}

/**
 * ท่าทางของดาวบนปุ่มเลือกดาว
 *   sleep  ยังไม่เคยไปเยี่ยม
 *   happy  ไปมาแล้ว
 *   star   ได้สามดาว สวมมงกุฎ
 * โลกตื่นอยู่เสมอ เพราะเราอยู่ที่นี่กันทุกคน
 */
export type BuddyStatus = 'sleep' | 'happy' | 'star'

export function buddyStatus(id: PlanetId, best: number | undefined, visited: readonly PlanetId[]): BuddyStatus {
  if (best === 3) return 'star'
  if (best !== undefined || visited.includes(id) || id === 'earth') return 'happy'
  return 'sleep'
}

/** ดาวที่ตื่นแล้วทั้งหมด ส่งให้ฉากสามมิติวาดหน้าตาให้ตรงกับปุ่ม */
export function awakePlanets(best: Partial<Record<PlanetId, number>>, visited: readonly PlanetId[]): PlanetId[] {
  return BUDDIES.map((buddy) => buddy.id).filter((id) => buddyStatus(id, best[id], visited) !== 'sleep')
}

