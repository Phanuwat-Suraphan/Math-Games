/** ตัวคูณที่เหตุการณ์กระทำกับทรัพยากรหนึ่งอย่าง */
export interface ResourceTweak {
  id: ResourceId
  multiplier: number
}

export interface DailyEvent {
  id: string
  emoji: string
  title: string
  detail: string
  /**
   * ผลกระทบเป็นถ้อยคำสั้น ๆ ที่บอกตัวเลขตรง ๆ
   *
   * แยกจาก detail ซึ่งเป็นการเล่าเรื่อง เพราะเด็กที่กำลังรีบวางแผน
   * ต้องอ่านบรรทัดเดียวแล้วรู้ว่าวันนี้ต้องทำอะไรต่างจากเมื่อวาน
   */
  effect: string
  /** ดีกับผู้เล่นไหม ใช้เลือกสีบนจอ null คือไม่มีผลทางตัวเลข */
  mood: 'good' | 'bad' | 'calm'
  /** ตัวคูณกำลังผลิตของวันนี้ */
  production?: ResourceTweak
  /** ตัวคูณปริมาณที่ต้องใช้ของวันนี้ */
  consumption?: ResourceTweak
  /** ตัวคูณราคาเมล็ดของวันนี้ */
  seedMultiplier?: number
  /** ตัวคูณราคาขายผลผลิตสดของวันนี้ ไม่แตะของแปรรูปกับผลผลิตจากสัตว์ */
  sellMultiplier?: number
}

