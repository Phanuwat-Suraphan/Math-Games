/**
 * เหตุการณ์ของวันนี้
 *
 * สุ่มจาก seed กับเลขวัน จึงได้ชุดเดิมทุกครั้งที่เรียก
 * ครูเปิดชุดเดียวกันให้ทั้งห้องดูพร้อมกันได้ และชุดทดสอบตรวจซ้ำได้
 */
export function eventForDay(farm: FarmState): DailyEvent {
  const rng = createRng(`farm-event-${farm.seed}-${farm.day}`)
  return rng.pick(EVENTS)
}

/** ตัวคูณราคาเมล็ดของวันนี้ */
export function seedMultiplier(farm: FarmState): number {
  return eventForDay(farm).seedMultiplier ?? 1
}

/** ตัวคูณราคาขายผลผลิตสดของวันนี้ */
export function sellMultiplier(farm: FarmState): number {
  return eventForDay(farm).sellMultiplier ?? 1
}

/**
 * ปรับกำลังผลิตและปริมาณที่ใช้ตามเหตุการณ์ของวันนี้
 *
 * ปัดเป็นจำนวนเต็มใกล้เคียงที่สุด เพราะทรัพยากรในเกมนี้ไม่มีเศษ
 *
 * ตอนแรกใช้ปัดลง ซึ่งฟังดูปลอดภัยกว่า แต่การปัดลงเอนไปทางผู้เล่นเสียเปรียบ
 * ทุกครั้งที่คูณ ทั้งฝั่งผลิตที่ถูกปัดลงและฝั่งใช้ที่ถูกปัดลงน้อยกว่าที่ควร
 * สะสมสามสิบวันแล้วกลายเป็นส่วนต่างที่มองไม่เห็นแต่วัดได้
 */
export function applyEvent(
  event: DailyEvent,
  production: Record<ResourceId, number>,
  consumption: Record<ResourceId, number>,
): { production: Record<ResourceId, number>; consumption: Record<ResourceId, number> } {
  const nextProduction = { ...production }
  const nextConsumption = { ...consumption }

  if (event.production) {
    const { id, multiplier } = event.production
    nextProduction[id] = Math.round(nextProduction[id] * multiplier)
  }
  if (event.consumption) {
    const { id, multiplier } = event.consumption
    nextConsumption[id] = Math.round(nextConsumption[id] * multiplier)
  }

  return { production: nextProduction, consumption: nextConsumption }
}
