/** หาเครื่องมือจากรหัส ใช้ตอนจะเอาคำแนะนำมาแสดง */
export function findTool(id: ToolId): ToolInfo {
  const found = TOOLS.find((tool) => tool.id === id)
  /* รายการข้างบนครบทุกรหัสอยู่แล้ว ตัวสำรองมีไว้กันกรณีเพิ่มรหัสใหม่แล้วลืมเติม */
  return found ?? TOOLS[0]
}

