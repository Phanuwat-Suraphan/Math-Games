/** ตัวชี้วัดหนึ่งตัวที่เกมนี้เก็บผลได้ */
export interface Indicator {
  id: IndicatorId
  /** รหัสตามหลักสูตร ว่างไว้เมื่อเป็นการทบทวนหรือต่อยอดที่ไม่ตรงตัวชี้วัดใด */
  code: string
  /** ชื่อสั้นสำหรับหัวตารางที่มีที่แคบ */
  short: string
  /** ข้อความเต็มตามหลักสูตร */
  full: string
  /**
   * ระดับของตัวชี้วัดเทียบกับชั้น ป.4
   *
   * core = ตัวชี้วัด ป.4 ที่เอกสารออกแบบตั้งใจวัด
   * review = ทบทวนของชั้นที่ต่ำกว่า ใช้เป็นด่านผ่านทาง ไม่ควรเอาไปกรอกคะแนน ป.4
   * extend = เกินชั้น ป.4 เด็กที่ทำได้คือทำได้เกินเกณฑ์ ไม่ใช่เกณฑ์ที่ต้องผ่าน
   * unlisted = เป็นเรื่องของชั้น ป.4 จริง แต่ทะเบียนนี้ยังไม่มีถ้อยคำของตัวชี้วัด
   *   ที่ยืนยันมาจากเอกสาร จึงยังไม่ใส่รหัสและยังไม่นับเป็นเกณฑ์
   *
   * ทำไมต้องมีระดับที่สี่ แทนที่จะยัดลงสองระดับที่มีอยู่
   *
   * เศษส่วนกับทศนิยมไม่ใช่การทบทวนของชั้นที่ต่ำกว่า และไม่ใช่เรื่องที่เกินชั้น ป.4
   * การติดป้ายว่าอย่างใดอย่างหนึ่งคือการเขียนข้อความที่ไม่จริงลงในทะเบียน
   * ที่ครูใช้เป็นเอกสารอ้างอิง ซึ่งแพงกว่าการเพิ่มระดับหนึ่งค่า
   * ในทางโค้ดมันทำตัวเหมือน review และ extend ทุกประการ คือไม่ถูกนับเป็นเกณฑ์
   */
  level: 'core' | 'review' | 'extend' | 'unlisted'
  /** true เมื่อรหัสมาจากเอกสารที่คุณครูเขียนเอง จึงยืนยันแล้ว */
  verified: boolean
}

