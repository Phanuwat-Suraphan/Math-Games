/** สิ่งที่ต้องรู้เกี่ยวกับโจทย์หนึ่งข้อ เพื่อตัดสินว่ามันวัดตัวชี้วัดไหน */
export interface SurvivorAnswer {
  skill: SkillId
  grade: number
  /** รูปทรงของโจทย์เรขาคณิต มาจาก metadata ของโจทย์ ไม่ได้แกะจากข้อความ */
  shape?: string
  /** จำนวนขั้นตอนของโจทย์ปัญหา มาจาก metadata เช่นกัน */
  steps?: number
}

/** รูปสี่เหลี่ยมมุมฉาก ซึ่งเป็นรูปเดียวที่ ค 2.1 ป.4/3 พูดถึง */
const RECTANGULAR_SHAPES = new Set(['square', 'rectangle'])

/**
 * ตัวชี้วัดของโจทย์หนึ่งข้อในสนามรบ คืน null เมื่อข้อนั้นไม่ได้วัดอะไรที่รายงานได้
 *
 * กติกาสองข้อที่ทำให้การรายงานนี้เชื่อถือได้
 *
 * หนึ่ง ตัวชี้วัดแกน (core) รับเฉพาะโจทย์ชั้น ป.4
 * สนามรบไล่ชั้นขึ้นเป็น ป.5 และ ป.6 ตามเลเวล การนับข้อ ป.6 เป็นตัวชี้วัด ป.4
 * คือการบอกครูว่าเด็กผ่านตัวชี้วัดชั้นนี้ ด้วยหลักฐานจากชั้นอื่น
 * ส่วนตัวทบทวนกับตัวต่อยอดไม่มีรหัสชั้นกำกับ จึงรับได้ทุกชั้น
 *
 * สอง เนื้อโจทย์ต้องตรงกับถ้อยคำของตัวชี้วัดจริง ๆ
 * ค 2.1 ป.4/3 พูดถึงรูปสี่เหลี่ยมมุมฉากเท่านั้น โจทย์สามเหลี่ยมกับวงกลม
 * ที่เครื่องสร้างโจทย์ผลิตออกมาด้วยจึงไม่นับ
 * ป.4/11 พูดถึงโจทย์สองขั้นตอน โจทย์ขั้นตอนเดียวจึงไม่นับ
 * ทั้งสองอย่างอ่านจาก metadata ที่เครื่องสร้างโจทย์ใส่มาให้ ไม่ได้แกะจากข้อความ
 * เพราะการแกะข้อความจะพังเงียบ ๆ ในวันที่มีคนแก้คำในโจทย์
 */
export function survivorIndicator(answer: SurvivorAnswer): IndicatorId | null {
  const id = SURVIVOR_INDICATOR[answer.skill]
  if (id === null) return null

  if (answer.skill === 'geometry' && !RECTANGULAR_SHAPES.has(answer.shape ?? '')) return null
  if (answer.skill === 'wordProblems' && (answer.steps ?? 1) < 2) return null

  if (findIndicator(id)?.level === 'core' && answer.grade !== 4) return null
  return id
}
