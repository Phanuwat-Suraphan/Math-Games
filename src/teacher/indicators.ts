export const INDICATOR_ORDER: readonly IndicatorId[] = INDICATORS.map((item) => item.id)

const BY_ID = new Map<IndicatorId, Indicator>(
  INDICATORS.map((item) => [item.id, item]),
)

/** คืนตัวชี้วัดตามรหัส ตัวที่ไม่รู้จักคืน null ให้ผู้เรียกตัดสินใจเอง */
export function findIndicator(id: string): Indicator | null {
  return BY_ID.get(id as IndicatorId) ?? null
}

/** ตัวชี้วัดที่ควรเอาไปกรอกคะแนนชั้น ป.4 ได้จริง */
export function coreIndicators(): readonly Indicator[] {
  return INDICATORS.filter((item) => item.level === 'core')
}

