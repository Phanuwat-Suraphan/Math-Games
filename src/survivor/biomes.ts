/** สนามที่ใช้เมื่อหาไอดีไม่เจอ เป็นสนามมาตรฐานเสมอ */
export const DEFAULT_BIOME = BIOMES[0] as Biome

export function getBiome(id: string): Biome {
  return BIOMES.find((biome) => biome.id === id) ?? DEFAULT_BIOME
}

/**
 * เลือกสนามของรอบหนึ่งจาก seed
 *
 * ใช้ seed ของรอบ ไม่ใช่ Math.random เพราะ seed เดิมต้องได้สนามเดิมเสมอ
 * ไม่งั้นการทดสอบจะเชื่อถือไม่ได้ และการเล่นซ้ำ seed เดิมจะได้คนละเกม
 */
export function biomeFor(seed: string): Biome {
  const rng = createRng(`biome-${seed}`)
  const index = rng.int(0, BIOMES.length - 1)
  return BIOMES[index] ?? DEFAULT_BIOME
}

/**
 * ข้อความบอกเด็กว่าสนามนี้ต่างจากปกติยังไง
 *
 * สร้างจากตัวเลขจริงทุกครั้ง ไม่มีข้อความที่พิมพ์มือแม้แต่สนามเดียว
 * เพราะถ้าพิมพ์มือ วันที่ใครไปแก้ตัวคูณ ข้อความจะค้างอยู่ที่เดิม
 * แล้วเกมจะบอกเด็กในสิ่งที่ไม่จริง ซึ่งเป็นความผิดพลาดชนิดเดียวกับ
 * เหตุการณ์ประจำวันของฟาร์มที่เคยเป็นข้อความประดับ
 *
 * บอกเป็นเปอร์เซ็นต์ด้วย เพราะนี่คือเกมคณิตศาสตร์
 * ตัวคูณ 1.3 ที่เขียนว่า "ถี่ขึ้น 30%" เป็นโจทย์เล็ก ๆ ที่เด็กอ่านผ่านทุกรอบ
 */
export function biomeBlurb(rules: BiomeRules): string {
  const pct = (value: number) => `${Math.round(Math.abs(value - 1) * 100)}%`
  const parts: string[] = []

  const say = (value: number, up: string, down: string) => {
    parts.push(`${value > 1 ? up : down} ${pct(value)}`)
  }

  if (rules.enemySpeed !== 1) say(rules.enemySpeed, 'มอนวิ่งเร็วขึ้น', 'มอนวิ่งช้าลง')
  if (rules.enemyHp !== 1) say(rules.enemyHp, 'มอนเลือดหนาขึ้น', 'มอนเลือดบางลง')
  if (rules.spawnRate !== 1) say(rules.spawnRate, 'มอนโผล่ถี่ขึ้น', 'มอนโผล่ห่างขึ้น')
  if (rules.xpValue !== 1) say(rules.xpValue, 'คริสตัลมากขึ้น', 'คริสตัลน้อยลง')
  if (rules.dropChance !== 1) say(rules.dropChance, 'ของตกบ่อยขึ้น', 'ของตกน้อยลง')

  if (parts.length === 0) return 'สนามมาตรฐาน ไม่มีตัวคูณพิเศษ'
  return parts.join(' · ')
}
