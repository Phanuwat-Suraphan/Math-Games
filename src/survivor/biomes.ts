/**
 * ตัวคูณที่สนามหนึ่งกระทำกับตัวเลขของเกม
 *
 * ทุกช่องเป็นตัวคูณ ไม่ใช่ค่าดิบ เพื่อให้สนามใหม่ไม่ต้องรู้ค่าที่ปรับสมดุลไว้แล้ว
 * และเพื่อให้การปรับสมดุลหลักยังอยู่ที่เดียวคือตารางมอนกับ spawnPlan
 */
export interface BiomeRules {
  /** ตัวคูณความเร็วมอน */
  enemySpeed: number
  /** ตัวคูณเลือดมอน */
  enemyHp: number
  /** ตัวคูณความถี่ที่มอนโผล่ ยิ่งมากยิ่งโผล่ถี่ */
  spawnRate: number
  /** ตัวคูณคริสตัลที่มอนหนึ่งตัวให้ */
  xpValue: number
  /** ตัวคูณโอกาสที่ของจะตกจากมอน */
  dropChance: number
}

/** สีของสนาม ทุกช่องต้องสว่างพอให้เส้นขอบสีเข้มของมอนอ่านออก */
export interface BiomePalette {
  /** สีขอบบนของพื้น อ่านเป็นท้องฟ้าไกล ๆ */
  skyTop: string
  /** สีช่วงกลาง */
  skyMid: string
  /** สีขอบล่าง อ่านเป็นพื้นที่อยู่ใกล้ตัว */
  ground: string
  /** สีเส้นตาราง เขียนเป็น rgba เพราะต้องจางมาก */
  grid: string
  /** สีเขาไกล ๆ ที่ขอบฟ้า */
  hill: string
  /** สีทางเดิน */
  path: string
  leafTints: string[]
  flowerTints: string[]
  rockTints: string[]
}

/** ของประดับแต่ละชนิดมีกี่ชิ้นในสนามนี้ */
export interface BiomeProps {
  tree: number
  bush: number
  rock: number
  flower: number
  grass: number
}

export interface Biome {
  id: string
  name: string
  rules: BiomeRules
  palette: BiomePalette
  props: BiomeProps
}

