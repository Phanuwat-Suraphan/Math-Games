export type Phase = 'playing' | 'question' | 'choosing' | 'dead'

export interface WorldState {
  seed: string
  /** วินาทีที่ผ่านไปตั้งแต่เริ่ม */
  time: number
  player: PlayerEntity
  enemies: EnemyEntity[]
  projectiles: ProjectileEntity[]
  enemyShots: EnemyShot[]
  effects: Effect[]
  /** แอ่งบนพื้นที่ยังไม่หมดอายุ */
  pools: PoolEntity[]
  damageNumbers: DamageNumber[]
  particles: Particle[]
  /**
   * ความแรงที่จอสั่นอยู่ตอนนี้ 0 = นิ่ง
   *
   * เก็บไว้ในสถานะเกม ไม่ใช่ให้หน้าจอคิดเอง เพราะเหตุที่ทำให้จอสั่น
   * (บอสโผล่ ระเบิด โดนตี) เกิดขึ้นในเฟรมเดียวและอยู่ในเครื่องยนต์ทั้งหมด
   */
  shake: number
  /** เสียงที่ต้องเล่นในก้าวนี้ หน้าจออ่านแล้วทิ้ง */
  sounds: SoundCue[]
  /**
   * แสงวาบเต็มจอ ใช้กับเหตุการณ์ใหญ่อย่างสกิลวิเศษและบอสล้ม
   *
   * เก็บความเข้มกับสีไว้ในสถานะเกม ด้วยเหตุผลเดียวกับแรงสั่นของจอ
   * คือเหตุการณ์ที่ทำให้เกิดมันอยู่ในเครื่องยนต์ทั้งหมด
   * และเกิดขึ้นในเฟรมเดียว ถ้าไม่บันทึกไว้ หน้าจอจะไม่มีทางรู้
   */
  flash: { color: string; power: number }
  gems: GemEntity[]
  pickups: PickupEntity[]
  notices: Notice[]
  /** สกิลติดตัวที่เลือกมาแล้ว นับจำนวนชั้น */
  skills: Record<string, number>
  /** อาวุธที่ถืออยู่ พร้อมระดับของแต่ละชิ้น */
  weapons: Record<string, number>
  /** อาวุธที่กลายเป็นร่างสมบูรณ์แล้ว */
  evolved: string[]
  /**
   * หีบที่เปิดแล้วแต่ยังไม่ได้ใช้ เก็บไว้รอจนกว่าจะมีอาวุธพร้อม
   *
   * ที่ต้องเก็บไว้ได้ เพราะถ้าหีบใช้ได้เฉพาะ "ตอนที่พร้อมพอดี"
   * เด็กที่ล้มบอสได้ตั้งแต่นาทีแรกจะเสียหีบไปเปล่า ๆ ทั้งที่ทำได้ดี
   * แล้วพอพร้อมจริงตอนนาทีที่สาม ก็ต้องรอบอสตัวถัดไปอีก
   * จำลองแล้วพบว่าเงื่อนไขนี้ทำให้ร่างสมบูรณ์เกิดขึ้นแค่ 3 ครั้งใน 40 รอบ
   */
  chests: number
  /** วินาทีที่เหลือก่อนโจมตีครั้งถัดไป แยกตามอาวุธ */
  weaponCooldowns: Record<string, number>
  /** วินาทีที่เหลือก่อนมอนตัวใหญ่พิเศษโผล่ */
  eliteCooldown: number
  /** วินาทีที่เหลือก่อนบอสตัวถัดไปโผล่ */
  bossCooldown: number
  /** ล้มบอสไปแล้วกี่ตัว ใช้สรุปผลตอนจบ */
  bossesDown: number
  ultimate: UltimateState
  /** พลังถาวรที่ซื้อมาจากนอกรอบ ติดตัวมาตั้งแต่วินาทีแรก */
  perks: Record<string, number>
  /**
   * ฟื้นคืนชีพที่เหลือในรอบนี้
   *
   * เก็บเป็นจำนวนที่เหลือ ไม่ใช่ธงว่าใช้ไปแล้วหรือยัง
   * เผื่อวันหนึ่งมีของที่ให้ฟื้นได้มากกว่าหนึ่งครั้ง จะได้ไม่ต้องรื้อโครงสร้าง
   */
  revivesLeft: number
  /** วินาทีที่เหลือก่อนมอนกลุ่มถัดไปโผล่ */
  spawnCooldown: number
  nextId: number
  phase: Phase
  kills: number
  /** ทักษะที่โจทย์ตอนเลเวลอัปครั้งถัดไปจะถาม */
  pendingSkill?: SkillId
  /** ตอบโจทย์ล่าสุดถูกไหม ใช้ตัดสินว่าจะให้เลือกสกิลกี่ใบ */
  lastAnswerCorrect: boolean
}

